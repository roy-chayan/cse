          <li><b>ক্যাশ মেমোরি:</b> CPU ও RAM-এর মাঝের অতি দ্রুত SRAM; বারবার লাগা উপাত্ত রেখে দুইয়ের গতির ব্যবধান কমায়; স্তর L1, L2, L3। RAM-এর তুলনায় দ্রুত, ছোট ও দামি।</li>
