    <p class="prose">সংরক্ষিত প্রোগ্রামের (Stored Program) ধারণা দেন হাঙ্গেরীয় বংশোদ্ভূত মার্কিন গণিতবিদ <b>জন ভন নিউম্যান</b> (John von Neumann), ১৯৪৫ সালে EDVAC কম্পিউটারের নকশার প্রতিবেদনে। তাই এ নকশাকে ভন নিউম্যান স্থাপত্য (von Neumann architecture) বলে। ENIAC-এর নির্মাতা একার্ট ও মকলিও এ ধারণার আলোচনায় যুক্ত ছিলেন।</p>
