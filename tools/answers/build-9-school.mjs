const [addRaw, subRaw, mulRaw] = [arith.slice(0, cutAt[0]), arith.slice(cutAt[0], cutAt[1]), arith.slice(cutAt[1])].map(s => s.trim());
const drop = (s, from, to) => { ok(s.includes(from), from); return "    " + s.replace(from, to); };
const add3 = drop(addRaw, `<p class="prose"><b>ক. যোগ:</b> (1011.1010)<sub>2</sub> + (10101.001)<sub>2</sub></p>\n    `, "");
const sub3 = drop(subRaw, `<b>খ. বিয়োগ:</b> (11010.110)<sub>2</sub> − (1010.101)<sub>2</sub>। `, "");
const mul3 = drop(mulRaw, `<b>গ. গুণ:</b> (1010)<sub>2</sub> × (101)<sub>2</sub>। `, "");
for (const [s, r] of [[add3, "100000.11"], [sub3, "10000.001"], [mul3, "110010"]]) ok(s.includes(`= (${r})<sub>2</sub>`), "result " + r);

