// Turns each sound file in sounds/ (answer-reveal.mp3 …) into a script the site can load, sounds/<name>.js.
//   node tools/sounds.mjs
// Why a script and not the .mp3 itself: a page opened straight from the disk (index.html, file://) isn't allowed to
// fetch files, but it may load scripts, which is how the rest of the site gets its data too. The script holds the
// sound as base64 text; app.js (SOUND in the rapid-fire part) turns it back into audio. Run this after replacing a
// sound file; tools/check-site.mjs reports a script that no longer matches its sound.
import fs from "node:fs";

const dir = new URL("../sounds/", import.meta.url);
const TYPES = { mp3: "audio/mpeg", wav: "audio/wav", ogg: "audio/ogg", m4a: "audio/mp4" };

export function soundScripts() {
  const out = {};
  for (const f of fs.readdirSync(dir).sort()) {
    const m = f.match(/^([\w-]+)\.(mp3|wav|ogg|m4a)$/);
    if (!m) continue;
    const b64 = fs.readFileSync(new URL(f, dir)).toString("base64");
    out[`${m[1]}.js`] = `/* Generated by tools/sounds.mjs from sounds/${f}; don't edit, replace the sound file and run it again.
   A script rather than the ${m[2]} itself, so the sound also plays when index.html is opened straight from the disk. */
(window.ICT_SOUNDS = window.ICT_SOUNDS || {})["${m[1]}"] = { type: "${TYPES[m[2]]}", data: "${b64}" };
`;
  }
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  for (const [name, text] of Object.entries(soundScripts())) {
    fs.writeFileSync(new URL(name, dir), text);
    console.log(`sounds/${name}: ${(text.length / 1024).toFixed(0)} KB`);
  }
}
